export const ALL_EMOJI: EmojiEntry[] = EMOJI_CATEGORIES.flatMap((c) => c.entries)

/**
 * Rank matches so a typed word finds the obvious emoji first.
 *
 * An exact keyword beats a prefix, which beats a substring — without that,
 * "cat" surfaces "communication" before 🐱. Ties then break on *where* the
 * keyword sits: the first keyword is the emoji's primary meaning, so "fire"
 * finds 🔥 (keywords "fire lit hot") ahead of ❤️‍🔥 ("heart on fire"), which
 * otherwise won purely by appearing earlier in the list.
 */
export function searchEmoji(query: string, limit = 90): EmojiEntry[] {
  const q = query.trim().toLowerCase()
  if (!q) return []

  const scored: { entry: EmojiEntry; score: number; at: number }[] = []
  const seen = new Set<string>()

  for (const entry of ALL_EMOJI) {
    // Some emoji sit in more than one category (🔥 is both nature and symbol).
    if (seen.has(entry.char)) continue

    const words = entry.keywords.split(' ')
    let score = 0
    let at = words.length

    const exact = words.indexOf(q)
    if (exact !== -1) {
      score = 3
      at = exact
    } else {
      const prefix = words.findIndex((w) => w.startsWith(q))
      if (prefix !== -1) {
        score = 2
        at = prefix
      } else if (entry.keywords.includes(q)) {
        score = 1
      }
    }

    if (score > 0) {
      seen.add(entry.char)
      scored.push({ entry, score, at })
    }
  }

  scored.sort((a, b) => b.score - a.score || a.at - b.at)
  return scored.slice(0, limit).map((s) => s.entry)
}
