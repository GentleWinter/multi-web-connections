/**
 * Emoji for the Ctrl+. picker.
 *
 * A curated set rather than the full Unicode table: the complete data with
 * names and keywords is megabytes, and a chat picker only ever needs the common
 * few hundred. Entries are written as "<char> <keywords…>" because that is far
 * less noisy to maintain than an object per emoji.
 */
export interface EmojiEntry {
  char: string
  keywords: string
}

export interface EmojiCategory {
  id: string
  label: string
  entries: EmojiEntry[]
}

function parse(raw: string[]): EmojiEntry[] {
  return raw.map((line) => {
    const space = line.indexOf(' ')
    return { char: line.slice(0, space), keywords: line.slice(space + 1) }
  })
}

